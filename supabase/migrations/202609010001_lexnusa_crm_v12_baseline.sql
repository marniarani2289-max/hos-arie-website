create extension if not exists pgcrypto;

create table if not exists public.lexnusa_admins (
  user_id uuid primary key references auth.users(id) on delete cascade,
  email text,
  display_name text,
  created_at timestamptz not null default now()
);

create table if not exists public.lexnusa_pilot_leads (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  name text not null check (char_length(name) between 1 and 120),
  organization text,
  email text not null check (char_length(email) <= 254),
  project_type text not null,
  message text not null check (char_length(message) between 1 and 6000),
  source text not null default 'lexnusa-landing',
  status text not null default 'new' check (status in ('new','contacted','qualified','won','lost','spam')),
  notes text check (notes is null or char_length(notes) <= 4000),
  notification_status text not null default 'pending',
  notification_provider_id text,
  notified_at timestamptz,
  consent_at timestamptz,
  consent_version text,
  follow_up_at timestamptz,
  estimated_value numeric(16,2) check (estimated_value is null or estimated_value >= 0),
  currency text not null default 'USD' check (currency in ('USD','IDR','SGD','MYR')),
  owner_user_id uuid references public.lexnusa_admins(user_id) on delete set null
);

create table if not exists public.lexnusa_lead_activities (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  lead_id bigint not null references public.lexnusa_pilot_leads(id) on delete cascade,
  actor_user_id uuid references auth.users(id) on delete set null,
  activity_type text not null,
  summary text not null check (char_length(summary) between 1 and 1000),
  details jsonb not null default '{}'::jsonb,
  constraint lexnusa_lead_activities_activity_type_check check (activity_type in (
    'created','status_changed','note_updated','follow_up_changed','value_changed','owner_changed',
    'email_opened','email_prepared','email_sent','email_sent_manual','email_failed','manual_note'
  ))
);

create table if not exists public.lexnusa_rate_limits (
  rate_key text primary key,
  window_started_at timestamptz not null default now(),
  request_count integer not null default 0 check (request_count >= 0)
