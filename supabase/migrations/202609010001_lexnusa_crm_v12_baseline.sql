create or replace function public.lexnusa_check_rate_limit(p_key text, p_limit integer, p_window_seconds integer)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  current_row public.lexnusa_rate_limits%rowtype;
  now_ts timestamptz := now();
begin
  if p_key is null or p_key = '' or p_limit < 1 or p_window_seconds < 1 then
    return false;
  end if;

  insert into public.lexnusa_rate_limits(rate_key, window_started_at, request_count)
  values (p_key, now_ts, 1)
  on conflict (rate_key) do nothing;

  select * into current_row
  from public.lexnusa_rate_limits
  where rate_key = p_key
  for update;

  if current_row.window_started_at <= now_ts - make_interval(secs => p_window_seconds) then
    update public.lexnusa_rate_limits
      set window_started_at = now_ts, request_count = 1
      where rate_key = p_key;
    return true;
  end if;

  if current_row.request_count >= p_limit then
    return false;
  end if;

  update public.lexnusa_rate_limits
    set request_count = request_count + 1
    where rate_key = p_key;
  return true;
end;
$$;

revoke all on function public.lexnusa_check_rate_limit(text, integer, integer) from public, anon, authenticated;
grant execute on function public.lexnusa_check_rate_limit(text, integer, integer) to service_role;
